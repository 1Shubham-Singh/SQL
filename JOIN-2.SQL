--=================================================================
--LEFT ANTI JOIN --RETURNS ROW FROM LEFT THAT HAS NO MATCH IN RIGHT
--=================================================================
--IN LEFT ANTI JOIN IF WE ARE POPULATING THE NULL VALUES FROM LEFT 
--TABLE WHILE USING WHERE CONDITION IS NULL THEN THAT IS CALLED LEFT ANTI JOIN
--THIS WILL NOT GIVE THE CORRECT RESULT BECAUSE WE DON'T HAVE RECORD IN THE TABLE
--GIVE ME NAME OF EMPLOYEE WHO HAS NOT ASSIGN TO ANY PROJECT


SELECT *
FROM DEPARTMENT AS D
LEFT JOIN MANAGER AS M 
ON D.DEPT_ID = M.DEPT_ID
WHERE M.DEPT_ID IS NULL;

--=================================================================
--RIGHT ANTI JOIN --RETURNS ROW FROM LEFT THAT HAS NO MATCH IN RIGHT
--=================================================================
--RETURNS ROWS FROM RIGHT THAT HAS NO MATCH IN LEFT

SELECT *
FROM DEPARTMENT AS D
RIGHT JOIN MANAGER AS M 
ON D.DEPT_ID = M.DEPT_ID
WHERE D.DEPT_ID IS NULL;

--TASK-1 GIVE ME SAME OUTPUT BY USING THE LEFT JOIN 
SELECT *
FROM MANAGER AS M 
LEFT JOIN  DEPARTMENT AS D
ON D.DEPT_ID = M.DEPT_ID
WHERE D.DEPT_ID IS NULL;

